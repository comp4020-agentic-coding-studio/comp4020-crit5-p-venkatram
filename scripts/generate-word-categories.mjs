// Generates src/scripts/animals-generated.ts and src/scripts/things-generated.ts
// from Princeton WordNet's noun data (via the wordnet-db devDependency --
// freely licensed for use, copying, and redistribution; see the header of
// node_modules/wordnet-db/dict/data.noun). We don't ship wordnet-db or any
// WordNet reader to the browser -- it's used once here to produce plain
// string arrays, the same shape as the rest of this repo's word lists.
//
// WordNet tags every noun synset with a lexicographer category (its
// "lex_filenum", the second field of each data.noun line) -- "dog" is
// literally filed under noun.animal, "hammer" under noun.artifact. That
// structured tagging is what makes this a credible classification rather
// than a guess: https://wordnet.princeton.edu/documentation/lexnames5wn
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const dataNounPath = require.resolve("wordnet-db/dict/data.noun");

// Numeric lex_filenum -> category name, per WordNet's lexnames table
// (only the noun.* entries are listed; data.noun only contains nouns).
const LEX_NAMES = {
  "03": "noun.Tops",
  "04": "noun.act",
  "05": "noun.animal",
  "06": "noun.artifact",
  "07": "noun.attribute",
  "08": "noun.body",
  "09": "noun.cognition",
  "10": "noun.communication",
  "11": "noun.event",
  "12": "noun.feeling",
  "13": "noun.food",
  "14": "noun.group",
  "15": "noun.location",
  "16": "noun.motive",
  "17": "noun.object",
  "18": "noun.person",
  "19": "noun.phenomenon",
  "20": "noun.plant",
  "21": "noun.possession",
  "22": "noun.process",
  "23": "noun.quantity",
  "24": "noun.relation",
  "25": "noun.shape",
  "26": "noun.state",
  "27": "noun.substance",
  "28": "noun.time",
};

// "Animal" per the brief covers animals, birds, and insects -- all filed
// under noun.animal in WordNet.
const ANIMAL_CATEGORIES = new Set(["noun.animal"]);

// "Thing" means a concrete, nameable object -- artifacts, natural objects,
// food, plants, body parts, raw materials, and shapes. Deliberately leaves
// out people, places (handled by places.ts), and abstract categories
// (events, feelings, cognition, etc.) so a "thing" answer names an object,
// not a concept.
const THING_CATEGORIES = new Set([
  "noun.artifact",
  "noun.object",
  "noun.food",
  "noun.plant",
  "noun.body",
  "noun.substance",
  "noun.shape",
]);

function wordsFromLemmaField(tokens, wordCount) {
  const words = [];
  for (let i = 0; i < wordCount; i++) {
    // Each lemma is a (word, lex_id) pair; the word itself is the first of
    // the two. Multi-word lemmas use underscores ("komodo_dragon").
    words.push(tokens[i * 2].replace(/_/g, " "));
  }
  return words;
}

async function main() {
  const raw = await readFile(dataNounPath, "utf8");
  const animals = new Set();
  const things = new Set();

  for (const line of raw.split("\n")) {
    if (!line || line[0] === " ") continue; // license header / blank lines
    const parts = line.split(/\s+/);
    const lexFilenum = parts[1];
    const category = LEX_NAMES[lexFilenum];
    if (!category) continue;
    const wordCount = parseInt(parts[3], 16);
    const words = wordsFromLemmaField(parts.slice(4), wordCount);

    let target = null;
    if (ANIMAL_CATEGORIES.has(category)) target = animals;
    else if (THING_CATEGORIES.has(category)) target = things;
    if (!target) continue;

    for (const word of words) target.add(word.toLowerCase());
  }

  await writeGenerated("animals-generated.ts", "GENERATED_ANIMALS", animals);
  await writeGenerated("things-generated.ts", "GENERATED_THINGS", things);
}

async function writeGenerated(filename, exportName, set) {
  const sorted = [...set].sort();
  const output = `// Generated by scripts/generate-word-categories.mjs -- do not edit by hand.
// Source: Princeton WordNet 3.1 (see node_modules/wordnet-db/dict/data.noun
// for the license), filtered to nouns tagged with the matching
// lexicographer category. Re-run \`node scripts/generate-word-categories.mjs\`
// to refresh.
export const ${exportName}: string[] = ${JSON.stringify(sorted, null, 2)};
`;
  await writeFile(new URL(`../src/scripts/${filename}`, import.meta.url), output);
  console.log(`Wrote ${sorted.length} words to src/scripts/${filename}`);
}

await main();
